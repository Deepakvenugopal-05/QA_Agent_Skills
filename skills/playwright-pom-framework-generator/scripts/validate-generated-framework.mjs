#!/usr/bin/env node
/**
 * Scan generated E2E files for forbidden locators and secrets.
 * Usage: node validate-generated-framework.mjs --root <repo> --e2e <e2e-dir>
 */
import fs from "node:fs";
import path from "node:path";

function arg(name, fallback) {
  const idx = process.argv.indexOf(name);
  return idx >= 0 ? process.argv[idx + 1] : fallback;
}

function walk(dir, acc = []) {
  if (!fs.existsSync(dir)) return acc;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, acc);
    else acc.push(full);
  }
  return acc;
}

const FORBIDDEN = [
  { id: "mui-class", re: /\.Mui[A-Za-z0-9_-]+/ },
  { id: "xpath", re: /xpath=/ },
  { id: "first-dodge", re: /\.first\(\)/ },
  { id: "fixed-wait", re: /waitForTimeout\(/ },
  { id: "coordinate-click", re: /mouse\.click\(/ },
  { id: "server-import", re: /from ['"].*\.server['"]/ },
];

const SECRET = [
  { id: "password-literal", re: /password\s*[:=]\s*['"][^'"]+['"]/i },
  { id: "auth-token", re: /auth_token\s*=/ },
];

const root = path.resolve(arg("--root", process.cwd()));
const e2e = path.resolve(root, arg("--e2e", "e2e"));
const errors = [];
const warnings = [];

if (!fs.existsSync(e2e)) {
  process.stdout.write(`${JSON.stringify({ e2e, skipped: true, reason: "e2e directory not found" }, null, 2)}\n`);
  process.exit(0);
}

const files = walk(e2e).filter((file) => /\.(ts|js|mjs|json|md)$/.test(file));
for (const file of files) {
  const rel = path.relative(root, file).split(path.sep).join("/");
  const text = fs.readFileSync(file, "utf8");
  if (rel.includes("specs/generated/") && !text.includes("generated by playwright-pom-framework-generator")) {
    warnings.push(`${rel} missing generated banner`);
  }
  if (rel.includes("specs/curated/") && text.includes("generated by playwright-pom-framework-generator — do not edit")) {
    errors.push(`${rel} curated file marked generated; regeneration would be unsafe`);
  }
  for (const rule of FORBIDDEN) {
    if (rule.re.test(text) && !rel.endsWith(".md")) errors.push(`${rel} forbidden pattern ${rule.id}`);
  }
  for (const rule of SECRET) {
    if (rule.re.test(text) && !rel.endsWith(".md")) errors.push(`${rel} possible secret ${rule.id}`);
  }
}

const report = { e2e: path.relative(root, e2e).split(path.sep).join("/"), files: files.length, errors, warnings };
process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
if (errors.length) process.exit(1);
